#include <math.h>
#include "calcbasic.h"

float sum(float a, float b) {
    return a + b;
}

float sub(float a, float b) {
    return a - b;
}

float mult(float a, float b) {
    return a * b;
}

float div(float a, float b) {
    return a / b;
}

float powa(float a, float b) {
    return pow(a, b);
}
